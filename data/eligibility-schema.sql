CREATE TABLE IF NOT EXISTS notice_eligibility (
  notice_id INTEGER PRIMARY KEY,
  study_levels TEXT CHECK (study_levels IS NULL OR (json_valid(study_levels) AND json_type(study_levels) = 'array')),
  student_years TEXT CHECK (student_years IS NULL OR (json_valid(student_years) AND json_type(student_years) = 'array')),
  enrollment_statuses TEXT CHECK (enrollment_statuses IS NULL OR (json_valid(enrollment_statuses) AND json_type(enrollment_statuses) = 'array')),
  income_tiers TEXT CHECK (income_tiers IS NULL OR (json_valid(income_tiers) AND json_type(income_tiers) = 'array')),
  degree_levels TEXT CHECK (degree_levels IS NULL OR (json_valid(degree_levels) AND json_type(degree_levels) = 'array')),
  graduation_statuses TEXT CHECK (graduation_statuses IS NULL OR (json_valid(graduation_statuses) AND json_type(graduation_statuses) = 'array')),
  experience_min REAL,
  experience_max REAL,
  experience_required INTEGER CHECK (experience_required IN (0, 1)),
  gpa_minima TEXT CHECK (gpa_minima IS NULL OR (json_valid(gpa_minima) AND json_type(gpa_minima) = 'object')),
  age_min INTEGER,
  age_max INTEGER,
  requires_full_time INTEGER CHECK (requires_full_time IN (0, 1)),
  applicant_types TEXT CHECK (applicant_types IS NULL OR (json_valid(applicant_types) AND json_type(applicant_types) = 'array')),
  field_states TEXT NOT NULL CHECK (json_valid(field_states) AND json_type(field_states) = 'object'),
  evidence TEXT NOT NULL CHECK (json_valid(evidence) AND json_type(evidence) = 'object'),
  caveats TEXT NOT NULL CHECK (json_valid(caveats) AND json_type(caveats) = 'array'),
  version INTEGER NOT NULL DEFAULT 1,
  updated_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CHECK (experience_min IS NULL OR experience_min >= 0),
  CHECK (experience_max IS NULL OR experience_max >= experience_min),
  CHECK (age_min IS NULL OR age_min >= 0),
  CHECK (age_max IS NULL OR age_max >= age_min)
);
